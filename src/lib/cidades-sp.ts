/** Sem acento, minusculo — pra busca que acha "sao jose" digitando sem acento. */
export function semAcento(s: string): string {
  return s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();
}

const INDICE: ReadonlyArray<{ nome: string; chave: string }> = CIDADES_SP.map((nome) => ({
  nome,
  chave: semAcento(nome),
}));

/**
 * Posicao de cada frequente na lista acima. Serve pra ordenar o resultado por
 * relevancia em vez de alfabeto: digitar "sao" tem que trazer Sao Paulo antes
 * de Sao Bernardo, porque Sao Paulo e' de longe o mais pedido.
 */
const RANK_FREQUENTE = new Map<string, number>(
  CIDADES_FREQUENTES.map((nome, i) => [semAcento(nome), i]),
);

/**
 * Busca cidade pelo que a pessoa digitou.
 *
 * A ordem importa de verdade aqui. Em ordem alfabetica, digitar "san" devolve
 * oito "Santa Alguma Coisa" e Santos NUNCA aparece — e Santos e' litoral, que
 * a Pegue atende todo dia. Entao a fila e':
 *   1. cidade frequente que COMECA com o termo   (san -> Santos)
 *   2. qualquer cidade que comeca com o termo
 *   3. cidade frequente que CONTEM o termo
 *   4. qualquer cidade que contem o termo
 * Sem termo, devolve as frequentes.
 */
export function buscarCidades(termo: string, limite = 8): string[] {
  const t = semAcento(termo);
  if (!t) return CIDADES_FREQUENTES.slice(0, limite);

  const comecaFreq: Array<{ nome: string; rank: number }> = [];
  const comeca: string[] = [];
  const contemFreq: Array<{ nome: string; rank: number }> = [];
  const contem: string[] = [];

  for (const { nome, chave } of INDICE) {
    const rank = RANK_FREQUENTE.get(chave);
    if (chave.startsWith(t)) {
      if (rank === undefined) comeca.push(nome);
      else comecaFreq.push({ nome, rank });
    } else if (chave.includes(t)) {
      if (rank === undefined) contem.push(nome);
      else contemFreq.push({ nome, rank });
    }
  }

  const porRank = (l: Array<{ nome: string; rank: number }>) =>
    l.sort((a, b) => a.rank - b.rank).map((x) => x.nome);

  return [...porRank(comecaFreq), ...comeca, ...porRank(contemFreq), ...contem].slice(0, limite);
}

/** Cidade existe no estado? A tela nao deixa cotar cidade que nao esta na lista. */
export function cidadeValida(nome: string): boolean {
  const t = semAcento(nome);
  return INDICE.some((c) => c.chave === t);
}
